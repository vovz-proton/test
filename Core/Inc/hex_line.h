/**
  ******************************************************************************
  * @file    hex_line.h
  * @brief   Разбор одной строки Intel HEX (используется при обновлении по USB).
  ******************************************************************************
  */

#ifndef HEX_LINE_H
#define HEX_LINE_H

#include <stdint.h>

/** Максимальное число байт данных в одной записи: 64. */
#define HEX_LINE_MAX_DATA 64U

typedef struct
{
  uint32_t address;                     /*!< абсолютный адрес (с учётом типа 04) */
  uint8_t  type;                        /*!< 00 - данные, 01 - конец, 04 - старший адрес */
  uint8_t  length;                      /*!< число байт данных */
  uint8_t  data[HEX_LINE_MAX_DATA];     /*!< данные записи */
} HexLine;

/**
  * @brief  Разобрать строку Intel HEX.
  * @param  line      строка, начиная с ':' (пробелы и CR/LF по краям допустимы)
  * @param  out       результат разбора
  * @param  extended  состояние старших 16 бит адреса между строками; запись типа 04
  *                   его обновляет, остальные - используют
  * @retval 1 - строка корректна (включая контрольную сумму), 0 - ошибка формата
  */
uint8_t HexLine_Parse(const char *line, HexLine *out, uint32_t *extended);

#endif /* HEX_LINE_H */
